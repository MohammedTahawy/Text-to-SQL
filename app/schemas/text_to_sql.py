# ==============================================================================
# Text-to-SQL Request & Response Schemas
# Path: app/schemas/text_to_sql.py
# Purpose: Defines data structures for incoming user analytical questions,
#          returned query records, executive summaries, and interactive chart specifications.
# ==============================================================================

# Typing utilities for nested data structures
from typing import List, Dict, Any, Optional

# BaseModel: Pydantic base class for request/response serialization
# Field: Provides field metadata, defaults, and documentation
from pydantic import BaseModel, Field


class AskQuestionRequest(BaseModel):
    """
    Incoming request payload containing user analytical query.
    """
    # question: Natural language prompt in Arabic or English (e.g. 'Top 5 selling items this month')
    # Ellipsis (...) denotes that this field is required
    question: str = Field(..., description="The user's query in Arabic or English")
    
    # language: Desired response language ('ar' for Arabic, 'en' for English)
    language: str = Field("ar", description="Preferred response language ('ar' or 'en')")
    
    # include_chart: Flag indicating whether to generate interactive Chart.js / ApexCharts specs
    include_chart: bool = Field(True, description="Whether to generate chart visualization specs")


class ChartData(BaseModel):
    """
    Interactive visualization specifications ready for direct rendering
    in Chart.js, ApexCharts, or Vue dashboard components.
    """
    # chart_type: Recommended visualization type ('bar', 'line', 'pie', 'doughnut')
    chart_type: str = Field("bar", description="Type of chart: 'bar', 'line', 'pie', 'doughnut'")
    
    # title: Display title rendered above the chart
    title: str = Field(..., description="Title of the chart")
    
    # labels: X-axis categories or dimension names (e.g. product names, warehouse branches, months)
    labels: List[str] = Field(default_factory=list, description="X-axis or category labels")
    
    # datasets: Numeric metric values and series configurations
    datasets: List[Dict[str, Any]] = Field(default_factory=list, description="ApexCharts/Chart.js datasets")


class AskQuestionResponse(BaseModel):
    """
    Complete response payload returned to the frontend.
    """
    # question: The original prompt submitted by the user
    question: str
    
    # generated_sql: Sanitized, AST-validated SQL query with injected tenant isolation
    generated_sql: str
    
    # row_count: Number of records retrieved from the database
    row_count: int
    
    # data: List of record dictionaries extracted from database execution
    data: List[Dict[str, Any]]
    
    # explanation: Executive narrative summary generated by LLM explaining findings
    explanation: str
    
    # chart: Optional visualization specification object (or None if not applicable)
    chart: Optional[ChartData] = None
