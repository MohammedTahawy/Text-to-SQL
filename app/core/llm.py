# LLM Client & Inference Adapter Module
# Path: app/core/llm.py
# Purpose: Unified adapter class for Large Language Model inference.
#          Supports Groq (ultra-low latency OpenAI-compatible endpoint)
#          and official OpenAI endpoints with resilient fallback handling.
# ==============================================================================

# Standard logging module
import logging

# Time module for backoff sleeping
import time

# Regular expressions module
import re

# Threading module for thread-safe active concurrency limiting
import threading

# Typing utilities
from typing import List, Dict, Any, Optional

# OpenAI official client (Groq is 100% compatible with the OpenAI API specification)
from openai import OpenAI

# Application settings instance
from app.config import settings

# Logger instance
logger = logging.getLogger(__name__)

# Active concurrency limiter (prevents exceeding Groq TPM / RPM rate limits)
groq_concurrency_semaphore = threading.Semaphore(settings.GROQ_MAX_CONCURRENCY)


class LLMClient:
    """
    Adapter class providing a consistent interface for LLM completions.
    Dynamically initializes Groq or OpenAI clients based on active configuration.
    """

    def __init__(self):
        """
        Constructor: Resolves active provider and initializes client instance.
        """
        self.provider = settings.DEFAULT_LLM_PROVIDER.lower()
        self.client: Optional[OpenAI] = None
        self._init_client()

    def _init_client(self):
        """
        Initializes the underlying client connection.
        Prioritizes Groq if configured, otherwise falls back to OpenAI.
        """
        if self.provider == "groq" or (settings.GROQ_API_KEY and not settings.OPENAI_API_KEY):
            self.provider = "groq"
            logger.info("Initializing Groq LLM Client (OpenAI-compatible)")
            self.client = OpenAI(
                api_key=settings.GROQ_API_KEY,
                base_url=settings.GROQ_BASE_URL,
                default_headers={"User-Agent": "InfoSas-AI/1.0"}
            )
        elif self.provider == "openai" and settings.OPENAI_API_KEY:
            logger.info("Initializing OpenAI LLM Client")
            self.client = OpenAI(api_key=settings.OPENAI_API_KEY)
        else:
            if settings.GROQ_API_KEY:
                self.provider = "groq"
                self.client = OpenAI(
                    api_key=settings.GROQ_API_KEY,
                    base_url=settings.GROQ_BASE_URL,
                    default_headers={"User-Agent": "InfoSas-AI/1.0"}
                )
            elif settings.OPENAI_API_KEY:
                self.provider = "openai"
                self.client = OpenAI(api_key=settings.OPENAI_API_KEY)
            else:
                self.client = None

    def chat_completion(
        self,
        messages: List[Dict[str, str]],
        model: Optional[str] = None,
        temperature: float = 0.1,
        max_tokens: int = 1500,
        response_format: Optional[Dict[str, Any]] = None,
    ) -> str:
        """
        Sends a chat completion request to the active LLM provider.
        
        Parameters:
        - messages: Role-based conversational history list ([{'role': 'system'|'user', 'content': '...'}])
        - model: Target model name (defaults to provider settings if None)
        - temperature: Sampling temperature (0.0 to 1.0; low value enforces deterministic SQL output)
        - max_tokens: Maximum tokens allowed in the completion
        - response_format: Optional output constraint (e.g. {'type': 'json_object'})
        
        Returns:
        - String response content generated by the model.
        """
        if not self.client:
            self._init_client()
            if not self.client:
                raise ValueError("No valid LLM API Key configured (GROQ_API_KEY or OPENAI_API_KEY)")

        # Select target model identifier
        if self.provider == "groq":
            target_model = model or settings.GROQ_MODEL
        else:
            target_model = model or settings.OPENAI_MODEL

        # Prepare payload dictionary
        kwargs: Dict[str, Any] = {
            "model": target_model,
            "messages": messages,
            "temperature": temperature,
            "max_tokens": max_tokens,
        }

        if response_format:
            kwargs["response_format"] = response_format

        max_retries = 3
        with groq_concurrency_semaphore:
            logger.debug(f"Acquired Groq concurrency slot (active limit: {settings.GROQ_MAX_CONCURRENCY})")
            for attempt in range(max_retries + 1):
                try:
                    response = self.client.chat.completions.create(**kwargs)
                    content = response.choices[0].message.content or ""
                    return content.strip()
                except Exception as e:
                    err_str = str(e).lower()
                    # Resilient backoff: Groq TPM / RPM 429 RateLimitError
                    if "429" in err_str or "rate limit" in err_str:
                        if attempt < max_retries:
                            match = re.search(r"try again in ([\d\.]+)s", str(e), re.IGNORECASE)
                            wait_sec = float(match.group(1)) + 1.0 if match else (attempt + 1) * 6.0
                            logger.warning(f"Groq Rate limit (429) hit. Waiting {wait_sec:.2f}s before retry {attempt + 1}/{max_retries}...")
                            time.sleep(wait_sec)
                            continue
                    # Fallback resilience: Some open-weights models on Groq might reject response_format parameter
                    if response_format and "response_format" in err_str:
                        logger.warning(f"Retrying chat completion without response_format due to: {e}")
                        kwargs.pop("response_format", None)
                        response = self.client.chat.completions.create(**kwargs)
                        return (response.choices[0].message.content or "").strip()
                    raise e


# Centralized singleton instance
llm_client = LLMClient()
